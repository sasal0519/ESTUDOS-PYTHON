# Secao: 1.2 Operadores de Comparação

x, y = 5, 8

print("x == y →", x == y)   # False: 5 não é igual a 8
print("x != y →", x != y)   # True:  5 é diferente de 8
print("x >  y →", x >  y)   # False: 5 não é maior que 8
print("x <  y →", x <  y)   # True:  5 é menor que 8
print("x >= y →", x >= y)   # False: 5 não é ≥ 8
print("x <= y →", x <= y)   # True:  5 é ≤ 8
