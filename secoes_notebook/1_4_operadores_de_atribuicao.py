# Secao: 1.4 Operadores de Atribuição

n = 10
print("n =", n)          # Valor inicial: 10

n += 5;  print("n += 5  →", n)   # 10 + 5 = 15
n -= 3;  print("n -= 3  →", n)   # 15 - 3 = 12
n *= 2;  print("n *= 2  →", n)   # 12 * 2 = 24
n //= 4; print("n //= 4 →", n)   # 24 // 4 = 6
n **= 2; print("n **= 2 →", n)   # 6 ** 2 = 36
n %= 7;  print("n %= 7  →", n)   # 36 % 7 = 1
