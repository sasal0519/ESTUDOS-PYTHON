# Secao: 1.1 Operadores Aritméticos

a, b = 10, 3
# Atribuição múltipla: cria a=10 e b=3 em uma única linha

print("Adição       (+):", a + b)        # 13
print("Subtração    (-):", a - b)        # 7
print("Multiplicação(*):", a * b)        # 30
print("Divisão      (/):}", a / b)        # 3.3333... (float!)
print("Divisão inteira(//):", a // b)    # 3 (apenas a parte inteira)
print("Módulo (resto)(%):", a % b)       # 1 (10 = 3*3 + 1)
print("Exponenciação(**):", a ** b)      # 1000 (10³)
