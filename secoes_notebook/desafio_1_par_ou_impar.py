# ═══════════════════════════════════════════════════════════
# DESAFIO 1: PAR OU ÍMPAR
# ═══════════════════════════════════════════════════════════

# ─────────────────────────────────────────────────────────
# TESTE 1: Número par (exemplo do desafio)
# ─────────────────────────────────────────────────────────
numero = 2

if numero % 2 == 0:
    print("Par")
else:
    print("Ímpar")


# ─────────────────────────────────────────────────────────
# TESTE 2: Número ímpar (exemplo do desafio)
# ─────────────────────────────────────────────────────────
numero = 5

if numero % 2 == 0:
    print("Par")
else:
    print("Ímpar")


# ─────────────────────────────────────────────────────────
# TESTE 3: Outro número par
# ─────────────────────────────────────────────────────────
numero = 6

if numero % 2 == 0:
    print("Par")
else:
    print("Ímpar")


# ─────────────────────────────────────────────────────────
# TESTE 4: Zero (zero é par!)
# ─────────────────────────────────────────────────────────
numero = 0

if numero % 2 == 0:
    print("Par")
else:
    print("Ímpar")


# ─────────────────────────────────────────────────────────
# TESTE 5: Número negativo ímpar
# ─────────────────────────────────────────────────────────
numero = -3

if numero % 2 == 0:
    print("Par")
else:
    print("Ímpar")
